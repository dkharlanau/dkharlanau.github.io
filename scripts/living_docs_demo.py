#!/usr/bin/env python3
"""Synthetic self-describing tool: derive a short card and diagram from one contract.

No SAP connectivity, routing engine, or live enterprise data is used.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "frameworks/living-documentation/tool-manifest.json"
CARD = ROOT / "frameworks/living-documentation/generated/tool-card.md"
DIAGRAM = ROOT / "frameworks/living-documentation/generated/change-flow.mmd"


def load_contract() -> dict:
    contract = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if contract.get("contract") != "ldc/0.1":
        raise ValueError("Unsupported contract version")
    tool = contract.get("tool", {})
    if not tool.get("id") or not tool.get("purpose") or not tool.get("fields"):
        raise ValueError("Missing mandatory tool metadata")
    stages = contract.get("lifecycle", [])
    if len(stages) < 2 or any(
        not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", stage.get("id", ""))
        for stage in stages
    ):
        raise ValueError("Lifecycle must contain safe, unique step IDs")
    if len({stage["id"] for stage in stages}) != len(stages):
        raise ValueError("Duplicate lifecycle step IDs")
    return contract


def cell(value: object) -> str:
    return str(value).replace("|", r"\|").replace("\n", " ")


def card_text(contract: dict) -> str:
    tool = contract["tool"]
    lines = [
        "<!-- Generated by scripts/living_docs_demo.py; do not edit manually. -->",
        "# " + tool["name"],
        "",
        "**Purpose:** " + tool["purpose"],
        "",
        "**Audience:** " + tool["audience"],
        "",
        "**Use:** " + tool["command"],
        "",
        "## Inputs",
        "",
        "| Field | Required | Meaning |",
        "| --- | --- | --- |",
    ]
    for field in tool["fields"]:
        lines.append(
            f"| {cell(field['name'])} | {'Yes' if field['required'] else 'No'} "
            f"| {cell(field['meaning'])} |"
        )
    lines.extend([
        "",
        "**Result:** " + tool["result"],
        "",
        "**Limits:**",
    ])
    lines.extend("- " + limit for limit in tool["limitations"])
    lines.extend([
        "",
        "**Evidence:** " + tool["evidence"],
        "",
        "**Owner:** " + tool["owner"],
        "",
    ])
    return "\n".join(lines)


def diagram_text(contract: dict) -> str:
    stages = contract["lifecycle"]
    lines = ["flowchart LR"]
    for stage in stages:
        label = stage["label"].replace('"', "'")
        lines.append(f'  {stage["id"]}["{label}"]')
    for before, after in zip(stages, stages[1:]):
        lines.append(f"  {before['id']} --> {after['id']}")
    lines.append("")
    return "\n".join(lines)


def inspect_input(contract: dict, payload: dict) -> dict:
    if not isinstance(payload, dict):
        raise ValueError("Input must be a JSON object")
    missing = [
        field["name"]
        for field in contract["tool"]["fields"]
        if field["required"] and (
            field["name"] not in payload
            or payload[field["name"]] is None
            or (isinstance(payload[field["name"]], str)
                and not payload[field["name"]].strip())
        )
    ]
    return {
        "tool": contract["tool"]["id"],
        "status": "input_incomplete" if missing else "fields_present_not_route_proven",
        "missing_required_fields": missing,
        "warning": "Synthetic input check only; no SAP route is determined.",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=("describe", "inspect", "sync", "check"))
    parser.add_argument("--input", help="JSON payload for the inspect action")
    args = parser.parse_args()
    contract = load_contract()

    if args.action == "describe":
        print(json.dumps(contract, indent=2, ensure_ascii=False))
        return 0
    if args.action == "inspect":
        if not args.input:
            parser.error("inspect requires --input")
        payload = json.loads(Path(args.input).read_text(encoding="utf-8"))
        result = inspect_input(contract, payload)
        print(json.dumps(result, indent=2))
        return 0 if not result["missing_required_fields"] else 2

    generated = {
        CARD: card_text(contract),
        DIAGRAM: diagram_text(contract),
    }
    if args.action == "sync":
        for path, content in generated.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"Generated {path.relative_to(ROOT)}")
        return 0

    stale = []
    for path, expected in generated.items():
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            stale.append(str(path.relative_to(ROOT)))
    if stale:
        print("Stale derived documentation: " + ", ".join(stale), file=sys.stderr)
        print("Run: python3 scripts/living_docs_demo.py sync", file=sys.stderr)
        return 1
    print("Living documentation generated outputs are current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
